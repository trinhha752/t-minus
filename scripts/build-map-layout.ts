// scripts/build-map-layout.ts
// Builds data/map-layout.json: ordered station paths per line, plus x/y for
// every station in a 1000 x 1000 box. Run once (or when the MBTA changes a line):
//
//   npm run build:map
//
// Order comes from each route's canonical trip (the MBTA's "normal service"
// pattern), not from /stops?filter[route]. That list runs Ashmont branch then
// Braintree branch, so one polyline through it would draw a fake segment from
// Ashmont to North Quincy. Canonical trips give one clean path per branch.

import fs from "node:fs";
import path from "node:path";
import { mbtaFetchLive } from "../lib/mbta";
import { project, rawProject, type MapProjection } from "../lib/map-projection";
import type { RouteId, Station } from "../types";
import { ALL_ROUTES } from "../types";

const OUT = path.join(process.cwd(), "data", "map-layout.json");
const STATIONS = path.join(process.cwd(), "data", "stations.json");

const PARK_STREET = "place-pktrm";
/** Distance^EXPONENT. 1 = real geography. 0.6 gives downtown stations room on a phone. */
const EXPONENT = 0.6;
const BOX = 1000;
const PAD = 40;

type Rel = { data?: { id: string } | null };
type Res = { id: string; relationships?: Record<string, Rel & { data?: unknown }> };

async function branchesFor(route: RouteId): Promise<string[][]> {
  const patterns = await mbtaFetchLive({
    endpoint: "/route_patterns",
    params: { "filter[route]": route, "filter[direction_id]": "0", "filter[canonical]": "true" },
    key: "",
  });

  const branches: string[][] = [];
  for (const p of patterns.data as Res[]) {
    // Today's shuttles come back too; keep only this route's own patterns.
    if ((p.relationships?.route?.data as { id: string } | null)?.id !== route) continue;
    const tripId = (p.relationships?.representative_trip?.data as { id: string } | null)?.id;
    if (!tripId) continue;

    // /trips/:id is a single resource, not a list.
    const trip = (await mbtaFetchLive({
      endpoint: `/trips/${tripId}`,
      params: { include: "stops" },
      key: "",
    })) as unknown as { data: Res; included?: Res[] };

    const platforms = (trip.data.relationships?.stops?.data as unknown as { id: string }[]) ?? [];
    const parentOf = new Map(
      (trip.included ?? []).map((s) => [
        s.id,
        (s.relationships?.parent_station?.data as { id: string } | null)?.id ?? s.id,
      ])
    );
    const ids = platforms.map((s) => parentOf.get(s.id) ?? s.id);
    branches.push(ids.filter((id, i) => id !== ids[i - 1]));
  }
  if (!branches.length) throw new Error(`no canonical pattern for ${route}`);
  return branches;
}

async function main() {
  const stations = JSON.parse(fs.readFileSync(STATIONS, "utf8")) as Station[];
  const byId = new Map(stations.map((s) => [s.id, s]));
  const park = byId.get(PARK_STREET);
  if (!park) throw new Error("Park Street missing from data/stations.json; run npm run seed:stations");

  const paths = {} as Record<RouteId, string[][]>;
  for (const route of ALL_ROUTES) {
    paths[route] = await branchesFor(route);
    console.log(`${route}: ${paths[route].map((b) => `${b.length} stops`).join(" + ")}`);
  }

  const used = [...new Set(Object.values(paths).flat(2))];
  const missing = used.filter((id) => !byId.has(id));
  if (missing.length) throw new Error(`stations not in stations.json: ${missing.join(", ")}`);

  // Fit the spread-out points into the box, keeping the aspect ratio.
  const base = { lat0: park.lat, lon0: park.lon, exponent: EXPONENT };
  const raw = used.map((id) => rawProject(base, byId.get(id)!.lat, byId.get(id)!.lon));
  const minX = Math.min(...raw.map((p) => p.x)), maxX = Math.max(...raw.map((p) => p.x));
  const minY = Math.min(...raw.map((p) => p.y)), maxY = Math.max(...raw.map((p) => p.y));
  const scale = (BOX - 2 * PAD) / Math.max(maxX - minX, maxY - minY);
  const projection: MapProjection = {
    ...base,
    scale,
    offsetX: BOX / 2 - ((minX + maxX) / 2) * scale,
    offsetY: BOX / 2 - ((minY + maxY) / 2) * scale,
  };

  const out = {
    _note: "Generated by scripts/build-map-layout.ts. Do not edit by hand.",
    viewBox: `0 0 ${BOX} ${BOX}`,
    projection,
    paths,
    stations: Object.fromEntries(
      used.sort().map((id) => {
        const s = byId.get(id)!;
        const routes = ALL_ROUTES.filter((r) => paths[r].some((b) => b.includes(id)));
        return [id, { name: s.name, routes, ...project(projection, s.lat, s.lon) }];
      })
    ),
  };
  fs.writeFileSync(OUT, JSON.stringify(out, null, 2) + "\n");

  // How tappable is downtown on a 390px phone?
  const pts = Object.entries(out.stations);
  let closest = { d: Infinity, a: "", b: "" };
  for (let i = 0; i < pts.length; i++)
    for (let j = i + 1; j < pts.length; j++) {
      const d = Math.hypot(pts[i][1].x - pts[j][1].x, pts[i][1].y - pts[j][1].y);
      if (d < closest.d) closest = { d, a: pts[i][1].name, b: pts[j][1].name };
    }
  const px = (closest.d * 390) / BOX;
  console.log(`\n${pts.length} stations -> ${OUT}`);
  console.log(`closest pair: ${closest.a} / ${closest.b}, ${px.toFixed(1)}px apart on a 390px-wide map`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
